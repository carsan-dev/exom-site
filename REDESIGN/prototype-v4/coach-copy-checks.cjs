'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const app = fs.readFileSync(__dirname + '/app.js', 'utf8');
const factory = app.slice(app.indexOf('function createCoachCopyTimeline('), app.indexOf('function createStrategyTyping('));
const start = { offsetLeft: 64 }, end = { offsetLeft: 820 }, bridge = {};
const calls = [];
const timeline = { fromTo(...args) { calls.push(args); return this; } };
const context = vm.createContext({ innerWidth: 1265, gsap: { timeline(options) { assert.equal(options.paused, true); return timeline; } } });
vm.runInContext(factory, context);
assert.equal(context.createCoachCopyTimeline(start, end, bridge), timeline);
assert.equal(calls.length, 3);
assert.equal(calls[0][0], start);
assert.equal(calls[0][1].opacity, 1);
assert.equal(calls[0][2].opacity, 0);
assert.equal(calls[0][3] + calls[0][2].duration, .3);
assert.equal(calls[1][0], bridge);
assert.equal(calls[1][2].x(), 756);
assert.ok(calls[1][3] + calls[1][2].duration < 1, 'Sentence rests before the scene ends');
assert.equal(calls[2][0], end);
assert.equal(calls[2][1].opacity, 0);
assert.equal(calls[2][2].opacity, 1);
assert.equal(calls[2][3] + calls[2][2].duration, 1);
end.offsetLeft = 900;
assert.equal(calls[1][2].x(), 836, 'Destination follows responsive layout');
context.innerWidth = 390;
assert.equal(calls[0][2].x(), 0);
assert.equal(calls[1][2].x(), 0);
assert.equal(calls[2][1].x(), 0);
assert.ok(app.includes('copyTimeline.progress(filmStateValue.progress)'), 'Shared forward/reverse scene progress');
assert.ok(app.includes('copyTimeline.progress(0).invalidate().progress(filmStateValue.progress)'), 'Refresh recalculates from the initial state');
const html = fs.readFileSync(__dirname + '/index.html', 'utf8');
assert.ok(!app.includes('filmCanvas'), 'Coaching repetitions are independent of scroll');
assert.ok(!html.includes('data-sequence="coach"'));
assert.ok(html.includes('<video class="coach-video" data-src="assets/coaching.mp4" muted loop playsinline preload="none" aria-hidden="true" tabindex="-1"></video>'));
assert.ok(fs.statSync(__dirname + '/assets/coaching.mp4').size > 1000);
const exporter = fs.readFileSync(__dirname + '/build-strategy-video.cjs', 'utf8');
const exportCalls = [];
const runExport = (scene, result = { status: 0 }) => vm.runInNewContext(exporter, { __dirname, process: { argv: ['node', 'build-strategy-video.cjs', 'ffmpeg', scene] }, console: { log() {} }, require: name => name === 'node:child_process' ? { spawnSync(command, args) { exportCalls.push(args); return result; } } : require(name) });
runExport('coach');
assert.equal(exportCalls.length, 1);
assert.equal(exportCalls[0][exportCalls[0].indexOf('-ss') + 1], '0');
assert.equal(exportCalls[0][exportCalls[0].indexOf('-t') + 1], '3');
assert.ok(!exportCalls[0][exportCalls[0].indexOf('-vf') + 1].includes('curves='), 'Do not apply training exposure to coaching');
assert.ok(exportCalls[0].includes('-an') && exportCalls[0].includes('+faststart'));
assert.ok(exportCalls[0].at(-1).endsWith('coaching.mp4'));
assert.throws(() => runExport('invalid'), /Unknown scene/);
assert.throws(() => runExport('coach', { status: 1, stderr: 'encoder failed' }), /encoder failed/);
assert.equal((html.match(/No tienes que resolverlo todo por tu cuenta\./g) || []).length, 1);
assert.ok(html.includes('Tu plan.<br><em>A tu medida.</em>') && html.includes('Y yo,<br><em>a tu lado.</em>'));
const css = fs.readFileSync(__dirname + '/styles.css', 'utf8');
assert.ok(css.includes('.film-sequence .coach-video{object-position:center}'), 'Match the canvas/poster framing instead of inheriting the old right-aligned video style');
assert.ok(css.includes('body[data-motion="off"] .film-title,body[data-motion="off"] .film-bridge{opacity:1!important;transform:none!important}'));
const { gsap } = require('./assets/vendor/gsap.min.js');
const realContext = vm.createContext({ gsap, innerWidth: 1265 });
vm.runInContext(factory, realContext);
const initial = { opacity: 1, x: 0, offsetLeft: 64 }, final = { opacity: 1, x: 0, offsetLeft: 820 }, sentence = { x: 0 };
const realTimeline = realContext.createCoachCopyTimeline(initial, final, sentence);
try {
  for (const width of [1265, 390, 1265]) {
    realContext.innerWidth = width;
    realTimeline.progress(1).progress(0).invalidate().progress(1);
    assert.equal(final.opacity, 1);
    assert.equal(sentence.x, width <= 760 ? 0 : 756);
    realTimeline.progress(.55);
    assert.equal(final.opacity, 0, 'Late title stays hidden after refresh and reverse scroll');
    realTimeline.progress(0);
    assert.equal(initial.opacity, 1);
    assert.equal(sentence.x, 0);
  }
} finally { realTimeline.kill(); gsap.ticker.sleep(); }
console.log('PASS: coaching copy phases, responsive endpoints, actual GSAP reverse/refresh, shared sentence and static fallback.');
